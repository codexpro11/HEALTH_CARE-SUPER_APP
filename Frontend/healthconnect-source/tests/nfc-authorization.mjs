import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const errors = [];
const requests = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().includes('/api/v1/')) requests.push(request.url()); });
const origin = process.env.TEST_APP_URL || 'http://127.0.0.1:4173/';
const hash = process.env.TEST_HASH_ROUTER === 'true' ? '#' : '';
const root = origin.replace(/\/$/, '');
const go = route => page.goto(root + (hash ? '/#' : '') + route, { waitUntil: 'domcontentloaded' });
const provider = async () => {
  await page.getByRole('button', { name: 'Role: PATIENT' }).click();
  await page.getByRole('button', { name: 'DOCTOR', exact: true }).click();
  await page.waitForURL('**/provider/nfc-scanner');
};
const patient = async () => {
  await page.getByRole('button', { name: 'Return to Patient Demo' }).click();
  await page.waitForURL('**/app/dashboard');
  await go('/app/nfc');
};
const scan = async () => {
  await page.getByRole('button', { name: '[ Start NFC Scan ]', exact: true }).click();
  await page.waitForURL('**/provider/nfc/summary/PT-1002');
  await page.getByRole('heading', { name: 'Patient Access Summary' }).waitFor();
};
await mkdir('test-results', { recursive: true });
try {
  await go('/provider/nfc/summary/PT-1002');
  await page.getByRole('button', { name: 'Sign In', exact: true }).waitFor();
  await page.getByLabel('Email Address', { exact: true }).fill('nfc.demo@healthconnect.example');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await go('/provider/nfc/summary/PT-1002');
  await page.waitForURL('**/app/dashboard');
  await go('/app/nfc');
  await page.getByText('ACTIVE', { exact: true }).waitFor();
  const firstId = await page.locator('p.font-mono').first().textContent();
  await provider();
  await go('/provider/nfc/summary/PT-1002');
  await page.getByRole('heading', { name: 'Patient access denied' }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Insurance Information' }).count(), 0);
  await page.getByRole('button', { name: 'Return to Scanner' }).click();
  await scan();
  await page.getByRole('heading', { name: 'Insurance Information' }).waitFor();
  await page.screenshot({ path: 'test-results/nfc-authorized.png', fullPage: true });
  await go('/provider/nfc/summary/other-patient');
  await page.getByRole('heading', { name: 'Patient access denied' }).waitFor();
  await go('/app/medical-records');
  await page.waitForURL('**/provider/nfc-scanner');
  await page.getByLabel('Demo reader scenario').selectOption('wrong-hospital');
  await page.getByRole('button', { name: '[ Start NFC Scan ]', exact: true }).click();
  await page.getByText('Access denied', { exact: true }).waitFor();
  await page.getByText('The provider is not associated with this authorized demo hospital.').waitFor();
  await patient();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revoke Card', exact: true }).click();
  await page.getByText('REVOKED', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByText('REVOKED', { exact: true }).waitFor();
  await provider();
  await page.getByRole('button', { name: '[ Start NFC Scan ]', exact: true }).click();
  await page.getByText('This NFC card has been revoked.').waitFor();
  await patient();
  await page.getByRole('button', { name: 'Activate New Card', exact: true }).click();
  await page.getByText('ACTIVE', { exact: true }).waitFor();
  assert.notEqual(await page.locator('p.font-mono').first().textContent(), firstId);
  await go('/app/consent');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revoke Access', exact: true }).first().click();
  await page.getByText('Revoked', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByText('Revoked', { exact: true }).waitFor();
  await provider();
  await page.getByRole('button', { name: '[ Start NFC Scan ]', exact: true }).click();
  await page.getByText('The patient has not granted active consent to this provider and facility.').waitFor();
  await patient();
  await go('/app/consent');
  await page.getByRole('button', { name: 'Manage Access', exact: true }).first().click();
  for (const name of ['Medical Summary', 'Prescriptions', 'Diagnostic Reports', 'Insurance']) {
    await page.getByRole('dialog').getByLabel(name, { exact: true }).uncheck();
  }
  await page.getByRole('button', { name: 'Save Access Permissions', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await provider();
  await scan();
  assert.equal(await page.getByRole('heading', { name: 'Insurance Information' }).count(), 0);
  assert.equal(await page.getByRole('heading', { name: 'Medical Summary', exact: true }).count(), 0);
  await page.getByText('Basic Profile', { exact: true }).waitFor();
  await go('/provider/nfc/emergency');
  const authorize = page.getByRole('button', { name: 'Authorize Emergency Access' });
  assert.equal(await authorize.isDisabled(), true);
  await page.getByLabel('Reason for Emergency Access').fill('Short');
  assert.equal(await authorize.isDisabled(), true);
  await page.getByLabel('Reason for Emergency Access').fill('Unconscious demo patient needs critical details');
  await authorize.click();
  await page.waitForURL('**/provider/nfc/summary/PT-1002');
  await page.getByText('Emergency Access · Demo', { exact: true }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Insurance Information' }).count(), 0);
  await page.screenshot({ path: 'test-results/nfc-emergency-scoped.png', fullPage: true });
  await page.evaluate(() => { const now = Date.now; Date.now = () => now() + 6 * 60 * 1000; window.dispatchEvent(new Event('focus')); });
  await page.getByRole('heading', { name: 'Patient access denied' }).waitFor();
  await page.screenshot({ path: 'test-results/nfc-access-expired.png', fullPage: true });
  await patient();
  await page.getByText('GRANTED · EMERGENCY', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/nfc-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('button', { name: 'Sign In', exact: true }).waitFor();
  await page.getByLabel('Email Address', { exact: true }).fill('other.demo@healthconnect.example');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await go('/app/nfc');
  await page.getByText('No access attempts yet.', { exact: true }).waitFor();
  assert.notEqual(await page.locator('p.font-mono').first().textContent(), firstId);
  await page.getByRole('button', { name: 'Role: PATIENT' }).click();
  await page.getByRole('button', { name: 'PHARMACY', exact: true }).click();
  await page.waitForURL('**/workspace');
  await go('/app/medical-records');
  await page.waitForURL('**/workspace');
  assert.equal(await page.getByRole('heading', { name: 'Medical Records', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  console.log('NFC authorization browser checks passed: anonymous and role guards, direct/wrong-patient URLs, hospital denial, persistent revocation/replacement, consent denial and scope filtering, emergency reason and expiry, account isolation, mobile card, and zero backend requests.');
} finally {
  await page.screenshot({ path: 'test-results/nfc-final-state.png', fullPage: true }).catch(() => {});
  await browser.close();
}
