import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch();
const context = await browser.newContext({ timezoneId: 'Asia/Kolkata', viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const origin = (process.env.TEST_APP_URL || 'http://127.0.0.1:4173').replace(/\/$/, '');
const hash = process.env.TEST_HASH_ROUTER === 'true' ? '/#' : '';
const go = path => page.goto(origin + hash + path, { waitUntil: 'domcontentloaded' });
const errors = [];
const requests = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().includes('/api/v1/')) requests.push(request.url()); });
const doctor = async () => {
  await page.getByRole('button', { name: 'Role: PATIENT' }).click();
  await page.getByRole('button', { name: 'DOCTOR', exact: true }).click();
  await page.waitForURL('**/provider/nfc-scanner');
};
await mkdir('test-results', { recursive: true });
try {
  await go('/provider/dashboard');
  await page.getByRole('button', { name: 'Sign In', exact: true }).waitFor();
  await page.getByLabel('Email Address', { exact: true }).fill('provider.qa@healthconnect.example');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await go('/provider/appointments');
  await page.waitForURL('**/app/dashboard');
  await doctor();
  await go('/provider/progress');
  await page.getByRole('heading', { name: 'Phases & Side-by-side Changes' }).waitFor();
  await page.screenshot({ path: 'test-results/provider-changes.png', fullPage: true });
  await go('/provider/dashboard');
  await page.getByRole('heading', { name: 'Doctor Workspace' }).waitFor();
  await go('/provider/appointments');
  await page.getByLabel('Demo doctor', { exact: true }).selectOption('doc-001');
  await page.getByLabel('Appointment status', { exact: true }).selectOption('CONFIRMED');
  await page.locator('a[href*="/provider/appointments/"]').first().click();
  await page.getByRole('button', { name: 'Start Consultation', exact: true }).click();
  await page.getByLabel('Clinical notes', { exact: true }).fill('Discussed the patient history and planned a follow-up demo visit.');
  await page.getByLabel('Demo prescription draft (optional)', { exact: true }).fill('Example draft only; no medicine issued.');
  await page.getByRole('button', { name: 'Save Consultation Draft', exact: true }).click();
  await page.getByText('Consultation draft saved in this browser.').waitFor();
  const appointmentId = page.url().split('/').pop();
  await page.reload();
  assert.match(await page.getByLabel('Clinical notes', { exact: true }).inputValue(), /follow-up demo visit/);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Complete Demo Consultation', exact: true }).click();
  await page.reload();
  assert.equal(await page.getByLabel('Clinical notes', { exact: true }).isDisabled(), true);
  await page.screenshot({ path: 'test-results/provider-consultation.png', fullPage: true });
  await go('/provider/prescriptions');
  await page.getByText('Example draft only; no medicine issued.', { exact: true }).waitFor();
  await go('/provider/appointments/not-this-account');
  await page.getByRole('heading', { name: 'Appointment unavailable', exact: true }).waitFor();

  await go('/provider/medical-records');
  await page.getByRole('heading', { name: 'Patient access required', exact: true }).waitFor();
  await go('/provider/nfc-scanner');
  await page.getByRole('button', { name: '[ Start NFC Scan ]', exact: true }).click();
  await page.waitForURL('**/provider/nfc/summary/PT-1002');
  await go('/provider/medical-records');
  await page.getByText('Showing standard record summaries within the current consent scopes.', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Return to Patient Demo', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await go('/app/appointments/' + appointmentId);
  await page.getByRole('heading', { name: 'Completed Demo Consultation', exact: true }).waitFor();
  await page.getByText('Example draft only; no medicine issued.', { exact: true }).waitFor();
  await go('/app/consent');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revoke Access', exact: true }).first().click();
  await doctor();
  await go('/provider/medical-records');
  await page.getByRole('heading', { name: 'Patient access required', exact: true }).waitFor();

  await page.getByRole('button', { name: 'Return to Patient Demo', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.getByRole('button', { name: 'Role: PATIENT' }).click();
  await page.getByRole('button', { name: 'HOSPITAL', exact: true }).click();
  await go('/provider/appointments');
  await page.getByRole('heading', { name: 'Doctor access required', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Return to Patient Demo', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await doctor();
  await go('/provider/dashboard');
  await page.setViewportSize({ width: 375, height: 667 });
  await page.getByRole('button', { name: 'Open provider menu', exact: true }).click();
  await page.getByRole('link', { name: 'Phases & Changes', exact: true }).click();
  await page.getByRole('heading', { name: 'Phases & Side-by-side Changes' }).waitFor();
  await page.screenshot({ path: 'test-results/provider-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  console.log('Provider workflow, persisted consultation, patient summary, consent and role boundaries, and mobile navigation passed.');
} finally {
  await browser.close();
}
